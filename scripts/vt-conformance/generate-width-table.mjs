#!/usr/bin/env node
/**
 * Generates android/app/src/main/java/com/scariflabs/horus/terminal/TerminalCharWidth.kt
 * from the Unicode 11 width tables of the pinned @xterm/addon-unicode11 (read
 * from its published source map), so NativeTerminalEngine measures characters
 * exactly as the xterm.js reference used by the VT conformance test does.
 *
 * Usage (from the repository root):
 *   node scripts/vt-conformance/generate-width-table.mjs
 */
import {readFileSync, writeFileSync} from 'node:fs';
import {dirname, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {createRequire} from 'node:module';

const require = createRequire(import.meta.url);
const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const addonDir = dirname(require.resolve('@xterm/addon-unicode11/package.json'));
const version = require('@xterm/addon-unicode11/package.json').version;
const map = JSON.parse(readFileSync(resolve(addonDir, 'lib/addon-unicode11.js.map'), 'utf8'));
const index = map.sources.findIndex(source => source.endsWith('/UnicodeV11.ts'));
if (index < 0) throw new Error('UnicodeV11.ts not found in the addon source map');
const source = map.sourcesContent[index];
const table = name => {
  const match = source.match(new RegExp(`const ${name} = (\\[[\\s\\S]*?\\]);`));
  if (!match) throw new Error(`table ${name} not found`);
  return Function(`return ${match[1]}`)();
};
const [bmpCombining, bmpWide, highCombining, highWide] =
  ['BMP_COMBINING', 'BMP_WIDE', 'HIGH_COMBINING', 'HIGH_WIDE'].map(table);
const inRanges = (cp, ranges) => ranges.some(([a, b]) => cp >= a && cp <= b);

// Mirrors UnicodeV11.wcwidth: BMP wide overrides combining; above the BMP
// combining is checked first.
function wcwidth(cp) {
  if (cp < 32) return 0;
  if (cp < 127) return 1;
  if (cp < 0x10000) {
    if (cp >= 0x7f && cp < 0xa0) return 0;
    if (inRanges(cp, bmpWide)) return 2;
    if (inRanges(cp, bmpCombining)) return 0;
    return 1;
  }
  if (inRanges(cp, highCombining)) return 0;
  if (inRanges(cp, highWide)) return 2;
  return 1;
}

// Runs of width != 1 from U+00A0 up; C0/C1/ASCII are handled by the parser.
const runs = [];
for (let cp = 0xa0; cp <= 0x10ffff; cp++) {
  const width = wcwidth(cp);
  if (width === 1) continue;
  const last = runs[runs.length - 1];
  if (last && last[1] === cp - 1 && last[2] === width) last[1] = cp;
  else runs.push([cp, cp, width]);
}
const hex = value => `0x${value.toString(16).toUpperCase()}`;
const rows = [];
for (let i = 0; i < runs.length; i += 4) {
  rows.push('    ' + runs.slice(i, i + 4).map(([a, b, w]) => `${hex(a)}, ${hex(b)}, ${w},`).join(' '));
}
const kotlin = `package com.scariflabs.horus.terminal

/**
 * Terminal cell width of a code point (0, 1 or 2), identical to the Unicode 11
 * provider of @xterm/addon-unicode11 ${version} that the VT conformance
 * reference runs with. GENERATED by scripts/vt-conformance/generate-width-table.mjs;
 * do not edit by hand.
 *
 * Only code points from U+00A0 are looked up: ASCII is width 1 and the
 * parser consumes C0/C1 controls before printing. The table is a sorted list
 * of non-overlapping [start, end, width] runs whose width is not 1, searched
 * without allocation.
 */
internal object TerminalCharWidth {
  fun of(codePoint: Int): Int {
    if (codePoint < 0xA0) return 1
    var low = 0
    var high = RUN_COUNT - 1
    while (low <= high) {
      val middle = (low + high) ushr 1
      val base = middle * 3
      when {
        codePoint < RUNS[base] -> high = middle - 1
        codePoint > RUNS[base + 1] -> low = middle + 1
        else -> return RUNS[base + 2]
      }
    }
    return 1
  }

  private val RUNS = intArrayOf(
${rows.join('\n')}
  )
  private val RUN_COUNT = RUNS.size / 3
}
`;
const out = resolve(root, 'android/app/src/main/java/com/scariflabs/horus/terminal/TerminalCharWidth.kt');
writeFileSync(out, kotlin);
console.log(`wrote ${runs.length} runs to ${out}`);
